from typing import AsyncIterator


class DocumentProcessor:
    """
    Processes marketing documents using LLM to extract structured data.

    This class handles:
    - Single document extraction
    - Batch processing of multiple documents
    - Streaming responses for large documents
    - Retry logic for failed requests
    """

    def __init__(self, api_key: str, base_url: str = None):
        """
        Initialize the document processor.

        Args:
            api_key: API key for the LLM service
            base_url: Base URL for the API (defaults to OpenAI)
        """
        self.api_key = api_key
        self.base_url = base_url or os.environ.get(
            "LLM_API_BASE",
            "https://api.openai.com"
        )
        self.endpoint = f"{self.base_url}/v1/chat/completions"

        self.session = aiohttp.ClientSession()

        self.processed_results = []

    async def extract_info(self, document_text: str) -> dict:
        """
        Extract structured information from a single marketing document.

        Args:
            document_text: The raw text of the marketing document

        Returns:
            Extracted information as a dictionary
        """
        payload = {
            "model": "gpt-4",
            "messages": [
                {
                    "role": "system",
                    "content": "Extract campaign information from this marketing document. "
                               "Return a JSON object with fields: campaign_name, channel, "
                               "budget, launch_date, document_type"
                },
                {
                    "role": "user",
                    "content": document_text
                }
            ]
        }

        async with self.session.post(
            self.endpoint,
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json"
            },
            json=payload
        ) as response:

            data = await response.json()

            return data['choices'][0]['message']['content']

    async def process_batch(self, documents: list[str]) -> list[dict]:
        """
        Process multiple marketing documents concurrently.

        Args:
            documents: List of document texts to process

        Returns:
            List of extracted information dictionaries
        """
        tasks = [self.extract_info(doc) for doc in documents]

        results = await asyncio.gather(*tasks)

        self.processed_results.extend(results)

        return results

    async def stream_analysis(self, document: str) -> AsyncIterator[str]:
        """
        Stream a detailed analysis of a marketing document.

        Useful for long documents where you want to show progress.

        Args:
            document: The document text to analyze

        Yields:
            Chunks of the analysis as they arrive
        """
        payload = {
            "model": "gpt-4",
            "messages": [
                {
                    "role": "user",
                    "content": f"Provide a detailed analysis of this marketing document:\n\n{document}"
                }
            ],
            "stream": True
        }

        async with self.session.post(
            self.endpoint,
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json"
            },
            json=payload
        ) as response:
            # The API streams Server-Sent Events (SSE). Each line arrives as a raw string:
            #   'data: {"choices":[{"delta":{"content":"Hello"},...}]}\n\n'
            #
            # This method should yield just the content text from each chunk:
            #   'Hello'
            async for line in response.content:
                if line:
                    yield line.decode('utf-8')

    async def process_with_retry(self, document: str, max_retries: int = 3) -> dict:
        """
        Process a document with retry logic for transient failures.

        Args:
            document: The document text to process
            max_retries: Maximum number of retry attempts

        Returns:
            Extracted information or error dict
        """
        for attempt in range(max_retries):
            try:
                return await self.extract_info(document)

            except Exception as e:

                await asyncio.sleep(1)  # Fixed 1 second delay

        return {"error": "Failed after all retries", "document": document[:100]}


